#!/usr/bin/env python3
"""
Henderson Innovations — client preview builder.

Reads the client records from H.I. Ground, copies every client site that has
an index.html into client-preview/sites/<slug>/, and regenerates
client-preview/auth.js.

Re-run this any time a new client site is finished or clients.json changes:

    python3 scripts/build_previews.py

Python standard library only. The H.I. Ground folder is read, never written.
"""

from __future__ import annotations

import datetime as _dt
import hashlib
import json
import os
import re
import shutil
import sys
from pathlib import Path

SCRIPT_DIR = Path(__file__).resolve().parent
REPO_ROOT = SCRIPT_DIR.parent
CLIENT_PREVIEW_DIR = REPO_ROOT / "client-preview"
SITES_DIR = CLIENT_PREVIEW_DIR / "sites"
AUTH_FILE = CLIENT_PREVIEW_DIR / "auth.js"

DEFAULT_CLIENTS_JSON = Path.home() / "Desktop" / "H.I. Ground" / "data" / "clients.json"
DEFAULT_SITES_SOURCE = Path.home() / "Desktop" / "business fair sites"

SLUG_RE = re.compile(r"^[a-z0-9]+(?:-[a-z0-9]+)*$")

# Internal working files live beside the client sites but are not part of the
# site itself. They are deliberately not published with the preview.
IGNORED_FILES = {
    ".DS_Store",
    "README.md",
    "research.md",
    "make_pdf.py",
    "debug.html",
    "test.txt",
    "SKIP.txt",
}
IGNORED_PREFIXES = ("_preview", "_csstest")
IGNORED_DIRS = {".git", "__pycache__", ".idea", ".vscode"}


def short(path: Path) -> str:
    """Home-relative path for tidy console output."""
    try:
        return "~/" + str(path.resolve().relative_to(Path.home()))
    except ValueError:
        return str(path)


def sha256_hex(value: str) -> str:
    return hashlib.sha256(value.encode("utf-8")).hexdigest()


def is_ignored_file(name: str) -> bool:
    return name in IGNORED_FILES or name.startswith(IGNORED_PREFIXES)


def sync_site(src: Path, dest: Path) -> tuple[int, int]:
    """Copy src into dest, updating only files that are new or changed.

    Mirrors `rsync -a` semantics (no deletions) while skipping internal notes.
    Returns (files_copied, total_site_files).
    """
    dest.mkdir(parents=True, exist_ok=True)
    copied = 0
    total = 0

    for root, dirnames, filenames in os.walk(src):
        dirnames[:] = sorted(d for d in dirnames if d not in IGNORED_DIRS)
        rel = Path(root).relative_to(src)
        target_root = dest / rel if rel != Path(".") else dest
        target_root.mkdir(parents=True, exist_ok=True)

        for filename in sorted(filenames):
            if is_ignored_file(filename):
                continue
            source_file = Path(root) / filename
            target_file = target_root / filename
            total += 1
            try:
                source_stat = source_file.stat()
                if target_file.exists():
                    target_stat = target_file.stat()
                    if (
                        target_stat.st_size == source_stat.st_size
                        and target_stat.st_mtime_ns == source_stat.st_mtime_ns
                    ):
                        continue
                shutil.copy2(source_file, target_file)
                copied += 1
            except OSError as exc:
                raise OSError(f"could not copy {source_file}: {exc}") from exc

    return copied, total


def load_clients(path: Path) -> list[dict]:
    with path.open("r", encoding="utf-8") as handle:
        data = json.load(handle)
    if not isinstance(data, list):
        raise ValueError("clients.json must contain a JSON array")
    return data


def build_auth_js(entries: list[dict], generated_on: str) -> str:
    version_hash = hashlib.sha256(
        json.dumps(entries, ensure_ascii=False, sort_keys=True).encode("utf-8")
    ).hexdigest()[:8]

    lines = [
        "/*",
        "  Henderson Innovations — Client Preview manifest",
        f"  Version: {generated_on} · {version_hash} · {len(entries)} client"
        + ("" if len(entries) == 1 else "s"),
        "",
        "  Generated by scripts/build_previews.py. Re-run that script after",
        "  clients.json changes or a client site is updated.",
        "",
        "  This file is hand-editable, but the generator will overwrite it.",
        "  Each entry:",
        "    u    login username (lowercase)",
        "    h    SHA-256 hex digest of the client's password",
        "    slug folder name under client-preview/sites/",
        "    name business name shown in the preview bar",
        "    t    session token: SHA-256 hex of (username + password + slug),",
        "         used by viewer.html to validate the stored session",
        "",
        "  If you hand-edit a password hash, update its t token to match.",
        "",
        "  Passwords are never stored here. The login page hashes what the",
        "  client types with Web Crypto and compares it to h. This is a",
        "  client-side preview gate, not server-grade access control.",
        "*/",
        "window.HI_PREVIEW_CLIENTS = [",
    ]

    for entry in entries:
        payload = json.dumps(entry, ensure_ascii=False, separators=(", ", ": "))
        lines.append(f"  {payload},")

    lines.append("];")
    lines.append(f'window.HI_PREVIEW_MANIFEST_VERSION = "{generated_on}";')
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    clients_json = DEFAULT_CLIENTS_JSON
    sites_source = DEFAULT_SITES_SOURCE

    print("Henderson Innovations — client preview build")
    print(f"  clients.json : {short(clients_json)}")
    print(f"  sites source : {short(sites_source)}")
    print(f"  output       : {short(CLIENT_PREVIEW_DIR)}")
    print()

    if not clients_json.exists():
        print(f"ERROR: clients.json not found at {clients_json}", file=sys.stderr)
        return 1
    if not sites_source.is_dir():
        print(f"ERROR: client site folder not found at {sites_source}", file=sys.stderr)
        return 1

    try:
        clients = load_clients(clients_json)
    except (OSError, ValueError, json.JSONDecodeError) as exc:
        print(f"ERROR: could not read clients.json: {exc}", file=sys.stderr)
        return 1

    SITES_DIR.mkdir(parents=True, exist_ok=True)

    entries: list[dict] = []
    seen_slugs: set[str] = set()
    seen_usernames: set[str] = set()
    skipped: list[tuple[str, str]] = []
    errors: list[tuple[str, str]] = []
    total_copied = 0

    for index, client in enumerate(clients, start=1):
        if not isinstance(client, dict):
            skipped.append((f"record {index}", "not an object"))
            continue

        business = str(client.get("business") or "").strip()
        slug = str(client.get("slug") or "").strip()
        username = str(client.get("username") or "").strip().lower()
        password = client.get("password")
        folder = str(client.get("folder") or "").strip()

        label = business or slug or f"record {index}"

        if not slug or not SLUG_RE.match(slug):
            skipped.append((label, "invalid or missing slug"))
            continue
        if not username or password is None or str(password) == "":
            skipped.append((label, "missing username or password"))
            continue
        if not folder:
            skipped.append((label, "missing folder path"))
            continue
        if slug in seen_slugs:
            skipped.append((label, f"duplicate slug '{slug}'"))
            continue
        if username in seen_usernames:
            skipped.append((label, f"duplicate username '{username}'"))
            continue

        source_dir = Path(folder).expanduser()
        if not source_dir.is_absolute():
            source_dir = (clients_json.parent / source_dir).resolve()
        if not source_dir.is_dir():
            skipped.append((label, "folder not found"))
            continue
        if not (source_dir / "index.html").is_file():
            skipped.append((label, "no index.html yet"))
            continue

        password = str(password)
        dest_dir = SITES_DIR / slug

        try:
            copied, total = sync_site(source_dir, dest_dir)
        except OSError as exc:
            errors.append((label, str(exc)))
            continue

        if not (dest_dir / "index.html").is_file():
            errors.append((label, "index.html missing after copy"))
            continue

        total_copied += copied
        seen_slugs.add(slug)
        seen_usernames.add(username)
        entries.append(
            {
                "u": username,
                "h": sha256_hex(password),
                "slug": slug,
                "name": business or slug,
                "t": sha256_hex(username + password + slug),
            }
        )

        note = f"{copied} file{'s' if copied != 1 else ''} updated" if copied else "up to date"
        print(f"  ✓ {label:<34} sites/{slug}  ({total} files, {note})")

    for label, reason in skipped:
        print(f"  · skipped {label}: {reason}")
    for label, reason in errors:
        print(f"  ! FAILED {label}: {reason}", file=sys.stderr)

    generated_on = _dt.date.today().isoformat()
    auth_js = build_auth_js(entries, generated_on)
    temp_auth = AUTH_FILE.with_suffix(".js.tmp")
    try:
        temp_auth.write_text(auth_js, encoding="utf-8")
        os.replace(temp_auth, AUTH_FILE)
    except OSError as exc:
        print(f"ERROR: could not write auth.js: {exc}", file=sys.stderr)
        return 1
    finally:
        if temp_auth.exists():
            temp_auth.unlink(missing_ok=True)

    print()
    print(f"  Clients in clients.json : {len(clients)}")
    print(f"  Preview sites built     : {len(entries)}")
    print(f"  Files copied/updated    : {total_copied}")
    print(f"  Manifest                : {short(AUTH_FILE)} ({len(entries)} entries, {generated_on})")
    if skipped:
        print(f"  Skipped                 : {len(skipped)}")
    if errors:
        print(f"  Errors                  : {len(errors)}", file=sys.stderr)
        return 1
    print("\nDone.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
